package main

import (
	"fmt"
	"math"
	"os"
	"strings"

	m "github.com/Eyevinn/dash-mpd/mpd"
)

// mpdSource is the ProgramInformation Source of generated MPDs. It also
// tells that an MPD may be overwritten.
const mpdSource = "Generated by livesim-content tools/contentgen"

// repResult is a written representation and what the MPD needs to know about it.
type repResult struct {
	pkg       *packaged
	codecs    string
	bandwidth uint32
	video     *VideoRep
	audio     *AudioRep
}

// writeMPD writes a static MPD. Video representations are grouped in one
// Adaptation Set per codec; every audio representation gets its own.
func writeMPD(c *Config, reps []*repResult, path string) error {
	mpd := m.NewMPD("static")
	mpd.Profiles = m.PROFILE_LIVE
	mpd.MediaPresentationDuration = m.Seconds2DurPtrFloat64(c.Duration)
	mpd.MinBufferTime = m.Seconds2DurPtrFloat64(c.MinBufferTime)
	maxSeg := 0.0
	for _, r := range reps {
		for _, s := range r.pkg.segs {
			maxSeg = max(maxSeg, float64(s.mpdDur)/float64(r.pkg.timescale))
		}
	}
	mpd.MaxSegmentDuration = m.Seconds2DurPtrFloat64(maxSeg)
	mpd.ProgramInformation = []*m.ProgramInformationType{{
		MoreInformationURL: "https://github.com/Dash-Industry-Forum/livesim-content",
		Title:              c.Title,
		Source:             mpdSource,
	}}
	period := &m.Period{Id: "P0", Start: m.Seconds2DurPtr(0)}
	mpd.Periods = []*m.Period{period}

	var asID uint32
	var asErr error
	newAS := func(contentType, mimeType string, rs []*repResult) *m.AdaptationSetType {
		if err := sameTiming(rs); err != nil && asErr == nil {
			asErr = err
		}
		as := &m.AdaptationSetType{Id: m.Ptr(asID), ContentType: m.RFC6838ContentTypeType(contentType),
			SegmentAlignment: true}
		asID++
		as.MimeType = mimeType
		as.StartWithSAP = 1
		as.SegmentTemplate = segmentTemplate(c, rs[0].pkg)
		return as
	}

	// Video: one Adaptation Set per codec, in config order.
	var codecOrder []string
	byCodec := make(map[string][]*repResult)
	for _, r := range reps {
		if r.video == nil {
			continue
		}
		if _, ok := byCodec[r.video.Codec]; !ok {
			codecOrder = append(codecOrder, r.video.Codec)
		}
		byCodec[r.video.Codec] = append(byCodec[r.video.Codec], r)
	}
	for _, codec := range codecOrder {
		rs := byCodec[codec]
		as := newAS("video", "video/mp4", rs)
		as.MaxFrameRate = c.Video.FPS.String()
		as.Roles = []*m.DescriptorType{m.NewRole("main")}
		par := ratio(rs[0].video.Width, rs[0].video.Height)
		for _, r := range rs {
			v := r.video
			as.MaxWidth = max(as.MaxWidth, uint32(v.Width))
			as.MaxHeight = max(as.MaxHeight, uint32(v.Height))
			if ratio(v.Width, v.Height) != par {
				par = ""
			}
			rep := &m.RepresentationType{Id: v.ID, Bandwidth: r.bandwidth}
			rep.Codecs = r.codecs
			rep.Width = uint32(v.Width)
			rep.Height = uint32(v.Height)
			rep.FrameRate = m.FrameRateType(c.Video.FPS.String())
			rep.Sar = "1:1"
			as.Representations = append(as.Representations, rep)
		}
		as.Par = m.RatioType(par)
		period.AdaptationSets = append(period.AdaptationSets, as)
	}

	// Audio: representations with the same codec, signal, language and label
	// are bitrate alternatives in one Adaptation Set. The first one is main.
	var groupOrder []string
	groups := make(map[string][]*repResult)
	for _, r := range reps {
		if r.audio == nil {
			continue
		}
		a := r.audio
		key := strings.Join([]string{a.Codec, a.Signal, a.Lang, a.Label}, "|")
		if _, ok := groups[key]; !ok {
			groupOrder = append(groupOrder, key)
		}
		groups[key] = append(groups[key], r)
	}
	for i, key := range groupOrder {
		rs := groups[key]
		a := rs[0].audio
		as := newAS("audio", "audio/mp4", rs)
		as.Lang = a.Lang
		role := "alternate"
		if i == 0 {
			role = "main"
		}
		as.Roles = []*m.DescriptorType{m.NewRole(role)}
		as.Labels = []*m.LabelType{{Value: a.Label}}
		for _, r := range rs {
			rep := &m.RepresentationType{Id: r.audio.ID, Bandwidth: r.bandwidth}
			rep.Codecs = r.codecs
			rate := m.UIntVectorType(fmt.Sprint(audioRate))
			rep.AudioSamplingRate = &rate
			if a.Codec == "ac3" {
				// Dolby channel configuration: A000 is L+R.
				rep.AudioChannelConfigurations = []*m.DescriptorType{
					m.NewDescriptor("tag:dolby.com,2014:dash:audio_channel_configuration:2011", "A000", "")}
			} else {
				rep.AudioChannelConfigurations = []*m.DescriptorType{
					m.NewDescriptor("urn:mpeg:dash:23003:3:audio_channel_configuration:2011", "2", "")}
			}
			as.Representations = append(as.Representations, rep)
		}
		period.AdaptationSets = append(period.AdaptationSets, as)
	}
	if asErr != nil {
		return asErr
	}

	out, err := mpd.WriteToString("  ", true)
	if err != nil {
		return err
	}
	return os.WriteFile(path, []byte(out), 0o644)
}

// sameTiming checks that the representations of an Adaptation Set have the
// same segments, since they share its SegmentTemplate.
func sameTiming(rs []*repResult) error {
	first := rs[0].pkg
	for _, r := range rs[1:] {
		p := r.pkg
		same := len(p.segs) == len(first.segs) && p.timescale == first.timescale
		for k := 0; same && k < len(p.segs); k++ {
			same = p.segs[k].start == first.segs[k].start && p.segs[k].mpdDur == first.segs[k].mpdDur
		}
		if !same {
			return fmt.Errorf("%s and %s are in the same Adaptation Set but have different segment timing; "+
				"give them different labels to put them in separate Adaptation Sets", first.id, p.id)
		}
	}
	return nil
}

// segmentTemplate returns the SegmentTemplate of an Adaptation Set. All its
// representations have the same segment timing, so p can be any of them.
func segmentTemplate(c *Config, p *packaged) *m.SegmentTemplateType {
	st := &m.SegmentTemplateType{Initialization: "$RepresentationID$/init.mp4"}
	st.Timescale = m.Ptr(p.timescale)
	if c.Addressing != AddrTimelineTime {
		st.StartNumber = m.Ptr(uint32(*c.StartNumber))
	}
	switch c.Addressing {
	case AddrNumber:
		st.Media = "$RepresentationID$/$Number$.m4s"
		st.Duration = m.Ptr(uint32(math.Round(c.SegmentDuration * float64(p.timescale))))
		return st
	case AddrTimelineTime:
		st.Media = "$RepresentationID$/$Time$.m4s"
	default:
		st.Media = "$RepresentationID$/$Number$.m4s"
	}
	st.SegmentTimeline = &m.SegmentTimelineType{}
	var last *m.S
	var next uint64
	for k, s := range p.segs {
		if last != nil && s.mpdDur == last.D && s.start == next {
			last.R++
		} else {
			last = &m.S{D: s.mpdDur}
			if k == 0 || s.start != next {
				last.T = m.Ptr(s.start)
			}
			st.SegmentTimeline.S = append(st.SegmentTimeline.S, last)
		}
		next = s.start + s.mpdDur
	}
	return st
}

// ratio returns the reduced aspect ratio, like "16:9".
func ratio(w, h int) string {
	a, b := w, h
	for b != 0 {
		a, b = b, a%b
	}
	return fmt.Sprintf("%d:%d", w/a, h/a)
}
